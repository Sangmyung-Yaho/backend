package com.sangmyungyaho.barocare.policy.entity;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

/**
 * 약관 및 정책 콘텐츠(프론트 화면 연동). 별도 DB 테이블 없이 코드 상수로 관리한다 - 해커톤 범위에서
 * 콘텐츠 변경 빈도가 낮고(법적 문서), 관리자 화면 없이 배포만으로 갱신해도 충분하기 때문이다.
 * 온보딩 필수 약관 동의 저장(OnboardingAgreementRequestDto, terms_agreed/privacy_agreed)은 "동의 여부"만
 * 다루고 이 enum과는 별개다 - 이 enum은 그 약관의 실제 "내용"을 조회용으로 제공한다.
 */
@Getter
@RequiredArgsConstructor
public enum PolicyType {

	TERMS("이용약관", "1.0", """
			제1조 (목적)
			이 약관은 바로케어(이하 "회사")가 제공하는 서비스의 이용과 관련하여 회사와 회원 간의 권리, 의무 및 책임사항을 규정함을 목적으로 합니다.

			제2조 (서비스의 제공)
			회사는 사용자의 피부 상태 분석, 생활습관 체크인, 원인 분석 리포트 및 케어 루틴 추천 서비스를 제공합니다.

			제3조 (회원가입)
			회원가입은 카카오, 구글 등 소셜 로그인을 통해 이루어지며, 회원은 가입 시 본 약관 및 개인정보처리방침에 동의해야 합니다.

			제4조 (회원의 의무)
			회원은 서비스 이용 시 관계 법령과 본 약관을 준수해야 하며, 타인의 정보를 도용하거나 서비스를 부정하게 이용해서는 안 됩니다.

			(본 약관은 해커톤/MVP 단계의 예시 콘텐츠이며, 실제 서비스 운영 시 법률 검토를 거친 내용으로 교체되어야 합니다.)
			"""),

	PRIVACY("개인정보처리방침", "1.0", """
			1. 수집하는 개인정보 항목
			회사는 소셜 로그인 정보(닉네임, 이메일 등 제공 동의 항목), 신체 정보(키, 몸무게, 피부 타입), 피부 촬영 이미지, 생활습관 체크인 데이터를 수집합니다.

			2. 개인정보의 수집 및 이용 목적
			수집한 정보는 피부 분석, 원인 리포트 생성, 케어 루틴 추천 등 서비스 제공 목적으로만 이용됩니다.

			3. 개인정보의 보유 및 이용 기간
			회원 탈퇴 시 관련 법령에 따른 보관 의무가 있는 정보를 제외하고 지체 없이 파기합니다.

			4. 개인정보의 제3자 제공
			회사는 원칙적으로 회원의 개인정보를 외부에 제공하지 않으며, 법령에 근거가 있는 경우에만 예외적으로 제공합니다.

			(본 방침은 해커톤/MVP 단계의 예시 콘텐츠이며, 실제 서비스 운영 시 법률 검토를 거친 내용으로 교체되어야 합니다.)
			""");

	private final String title;
	private final String version;
	private final String content;
}
